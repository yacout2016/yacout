SET NAMES utf8mb4;
DELETE FROM site_config WHERE config_key IN ('admin_gate_key', 'admin_otp', 'otp_login');
DELETE FROM login_attempts;
SELECT 'GRIFFINE: دخول الإدارة رجع زي الأول' AS result;
